def _style_hint(profile: Dict[str, Any]) -> str:
    langs = ", ".join(profile.get("languages") or []) or "english"
    parts = [f"language/style: {langs}", f"typical message length: {profile.get('avg_len', 0)} characters"]
    if profile.get("emoji_ratio", 0) > 0.3:
        parts.append("they use emojis often")
    if profile.get("roman_urdu_ratio", 0) > 0.3:
        parts.append("they write Roman Urdu casually")
    return "; ".join(parts)


async def generate_reply(chat: str) -> str:
    """Draft a reply that matches the chat's transcript and style."""
    chat = (chat or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    from . import llm  # local import: keep llm lazy

    if not llm.has_provider():
        raise WhatsAppError("reply generation requires a chat provider (Settings > Providers)", 409)
    body = transcript(chat)
    if not body:
        raise WhatsAppError("no messages in this chat yet")
    profile = style_profile(chat)
    system = (
        "You are replying inside a WhatsApp chat. Match the other person's "
        "language, tone and message length. Reply with at most 2 short lines - "
        "just the message text, no quotes, no signature, no explanation. "
        f"Chat style: {_style_hint(profile)}."
    )
    user = f"Recent messages:\n{body}\n\nWrite the next reply from me:"
    try:
        text, _provider = await llm.complete(
            [{"role": "system", "content": system}, {"role": "user", "content": user}],
            temperature=0.7,
            max_tokens=300,
        )
    except Exception as exc:  # noqa: BLE001 - provider failures are user-facing
        raise WhatsAppError(f"reply generation failed: {exc}", 409) from None
    text = (text or "").strip().strip('"').strip()
    if not text:
        raise WhatsAppError("the provider returned an empty reply")
    return text[:MAX_REPLY_CHARS]


