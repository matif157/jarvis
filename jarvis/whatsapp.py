def _cooldown_ok(chat: str) -> bool:
    cooldown = get_cooldown()
    if cooldown <= 0:
        return True
    last = db.last_outbound_ts_db(chat)
    if not last:
        return True
    try:
        sent = datetime.strptime(last[:19].replace("T", " ").rstrip("Z"), "%Y-%m-%d %H:%M:%S")
    except ValueError:
        return True
    # created_at is stored in UTC (db.now); compare in UTC, not local time
    now_utc = datetime.now(timezone.utc).replace(tzinfo=None)
    return (now_utc - sent).total_seconds() >= cooldown


def should_reply(chat: str) -> Dict[str, Any]:
    """Decide whether/how to reply in a chat. Honest reasons for 'no'."""
    chat = (chat or "").strip()
    if not get_listen():
        return {"ok": False, "mode": "off", "reason": "listening is disabled"}
    mode = rule_for(chat)
    if mode == "off":
        return {"ok": False, "mode": mode, "reason": "no rule set for this chat"}
    if mode == "auto" and not get_auto_reply():
        return {
            "ok": False,
            "mode": mode,
            "reason": "auto replies are disabled (Settings > WhatsApp)",
        }
    if mode == "auto" and not _cooldown_ok(chat):
        return {"ok": False, "mode": mode, "reason": "cooldown active"}
    if mode == "auto":
        status = bridge_status()
        if not status.get("supported"):
            return {"ok": False, "mode": mode, "reason": "sending replies requires the Android app"}
        if not status.get("listener"):
            return {"ok": False, "mode": mode, "reason": "notification listener is not enabled"}
        targets = [str(t) for t in status.get("targets") or []]
        if chat not in targets:
            return {"ok": False, "mode": mode, "reason": "no open reply target for this chat"}
    return {"ok": True, "mode": mode, "reason": ""}


