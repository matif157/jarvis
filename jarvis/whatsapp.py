def chats(limit: int = 500) -> List[Dict[str, Any]]:
    """Mapped structure of every chat: counts, last activity, rule."""
    rules = get_rules()
    out = []
    for row in db.list_wa_chats_db(limit):
        row = dict(row)
        row["rule"] = rules.get(row["chat"], "off")
        out.append(row)
    return out


def history(chat: str, limit: int = 100) -> Dict[str, Any]:
    """Chronological messages of one chat."""
    chat = (chat or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    messages = db.list_wa_messages_db(chat, max(1, min(int(limit or 100), 1000)))
    return {"chat": chat, "count": len(messages), "messages": messages}


def delete_chat(chat: str) -> int:
    """Remove every stored message of a chat plus its pending suggestion."""
    chat = (chat or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    db.forget_db(SUGGEST_KEY.format(chat=chat))
    return db.delete_wa_messages_db(chat)


_ROMAN_URDU = {
    "kya", "hai", "ho", "kaise", "kaisa", "kaisi", "nahi", "acha", "theek",
    "tum", "aap", "mera", "meri", "tera", "teri", "kyun", "kab", "kro",
    "karo", "bhai", "yaar", "shukriya", "salam", "wallah", "bas", "aur",
    "matlab", "pata", "chalo", "hoon", "hun", "raha", "rahi", "gaya",
}


def style_profile(chat: str, sample: int = 200) -> Dict[str, Any]:
    """Language/length fingerprint of a chat, used to style replies."""
    messages = [m for m in db.list_wa_messages_db(chat, sample) if m["direction"] != "system"]
    if not messages:
        return {
            "chat": chat, "count": 0, "avg_len": 0, "urdu_ratio": 0.0,
            "roman_urdu_ratio": 0.0, "emoji_ratio": 0.0, "languages": [],
        }
    texts = [m["text"] for m in messages]
    letters = sum(len(t) for t in texts) or 1
    urdu_chars = sum(1 for t in texts for ch in t if "\u0600" <= ch <= "\u06ff")
    roman_hits = sum(
        1 for t in texts
        if any(w.strip(".,!?").lower() in _ROMAN_URDU for w in t.split())
    )
    emoji_hits = sum(1 for t in texts if any(ord(ch) > 0x2000 and not ch.isalnum() and not ch.isspace() for ch in t))
    languages: List[str] = []
    if urdu_chars / letters > 0.15:
        languages.append("urdu")
    if roman_hits:
        languages.append("roman-urdu")
    if not languages or any(c.isascii() and c.isalpha() for c in "".join(texts)[:200]):
        languages.append("english")
    return {
        "chat": chat,
        "count": len(messages),
        "avg_len": int(round(letters / len(messages))),
        "urdu_ratio": round(urdu_chars / letters, 3),
        "roman_urdu_ratio": round(roman_hits / len(messages), 3),
        "emoji_ratio": round(emoji_hits / len(messages), 3),
        "languages": languages,
    }


def transcript(chat: str, limit: int = 40) -> str:
    """Recent messages as ``Sender: text`` lines, truncated for the model."""
    messages = [m for m in db.list_wa_messages_db(chat, limit) if m["direction"] != "system"]
    lines = []
    for m in messages:
        who = m["sender"] or ("me" if m["direction"] == "out" else "them")
        lines.append(f"{who}: {m['text']}")
    text = "\n".join(lines)
    return text[-TRANSCRIPT_CHARS:]


