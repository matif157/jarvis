# Suggestions
# ---------------------------------------------------------------------------
def set_suggestion(chat: str, text: str) -> Dict[str, Any]:
    chat = (chat or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    suggestion = {"text": (text or "").strip()[:MAX_REPLY_CHARS], "created_at": db.now()}
    db.remember_db(SUGGEST_KEY.format(chat=chat), suggestion)
    return {"chat": chat, **suggestion}


def get_suggestion(chat: str) -> Optional[Dict[str, Any]]:
    data = db.recall_db(SUGGEST_KEY.format(chat=(chat or "").strip()))
    if isinstance(data, dict) and data.get("text"):
        return data
    return None


def accept_suggestion(chat: str) -> Dict[str, Any]:
    """Send the stored suggestion for a chat and clear it."""
    suggestion = get_suggestion(chat)
    if not suggestion:
        raise WhatsAppError("no pending suggestion for this chat", 404)
    data = send_reply(chat, suggestion["text"])
    db.forget_db(SUGGEST_KEY.format(chat=(chat or "").strip()))
    return {"chat": chat.strip(), "text": suggestion["text"], **data}


def dismiss_suggestion(chat: str) -> Dict[str, Any]:
    chat = (chat or "").strip()
    if not get_suggestion(chat):
        raise WhatsAppError("no pending suggestion for this chat", 404)
    db.forget_db(SUGGEST_KEY.format(chat=chat))
    return {"chat": chat, "dismissed": True}


# ---------------------------------------------------------------------------
# Event orchestration
# ---------------------------------------------------------------------------
async def handle_event(event: Dict[str, Any]) -> Dict[str, Any]:
    """Record a live message and apply the chat's reply rule.

    Always returns a payload (the listener must not retry on rule misses);
    generation failures land in ``error`` without failing the recording.
    """
    result = record_event(event)
    if not result.get("stored"):
        return result
    chat = str(result["chat"])
    decision = should_reply(chat)
    result["reply"] = decision
    if not decision.get("ok"):
        return result
    try:
        text = await generate_reply(chat)
    except WhatsAppError as exc:
        result["error"] = str(exc)
        return result
    if decision["mode"] == "suggest":
        result["suggestion"] = set_suggestion(chat, text)["text"]
        return result
    try:
        send_reply(chat, text)
        result["replied"] = True
    except WhatsAppError as exc:
        # Fall back to a suggestion so the draft is not lost.
        result["error"] = str(exc)
        result["suggestion"] = set_suggestion(chat, text)["text"]
    return result


