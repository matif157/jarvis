def status_payload() -> Dict[str, Any]:
    """Combined report for ``GET /api/whatsapp/status``."""
    status = bridge_status()
    out: Dict[str, Any] = {
        "ok": True,
        "supported": bool(status.get("supported")),
        "messages": db.count_wa_messages_db(),
        "chats": len(db.list_wa_chats_db()),
        **settings_payload(),
    }
    out["listener"] = bool(status.get("listener"))
    out["targets"] = [str(t) for t in status.get("targets") or []]
    if status.get("error"):
        out["error"] = status["error"]
    if not out["supported"]:
        out["note"] = "live reading and replies require the Android app"
    return out
