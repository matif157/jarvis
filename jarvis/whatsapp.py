# 12/03/2024, 5:04 PM - Sender: message      (day/month/year, 12h or 24h)
LINE_RE = re.compile(
    r"^(\d{1,2})[/-](\d{1,2})[/-](\d{2,4}),\s+"
    r"(\d{1,2}):(\d{2})(?::\d{2})?\s*([AaPp][Mm])?\s+-\s+(.*)$"
)
# 12 March 2024, 17:04 - Sender: message     (long date, day first)
DAY_FIRST_RE = re.compile(
    r"^(\d{1,2})\s+([A-Za-z]{3,9})\s+(\d{2,4}),\s+"
    r"(\d{1,2}):(\d{2})(?::\d{2})?\s*([AaPp][Mm])?\s+-\s+(.*)$"
)
# March 12, 2024, 5:04 PM - Sender: message  (long date, month first)
MONTH_FIRST_RE = re.compile(
    r"^([A-Za-z]{3,9})\s+(\d{1,2}),?\s+(\d{2,4}),\s+"
    r"(\d{1,2}):(\d{2})(?::\d{2})?\s*([AaPp][Mm])?\s+-\s+(.*)$"
)
MONTHS = {
    "january": 1, "february": 2, "march": 3, "april": 4, "may": 5,
    "june": 6, "july": 7, "august": 8, "september": 9, "october": 10,
    "november": 11, "december": 12,
}


class WhatsAppError(RuntimeError):
    """User-facing WhatsApp failure; ``status`` maps to the HTTP code."""

    def __init__(self, message: str, status: int = 400):
        super().__init__(message)
        self.status = status


# ---------------------------------------------------------------------------
# Android bridge (mirrors the voice bridge pattern)
# ---------------------------------------------------------------------------
_backend: Optional[Any] = None
_probed = False
_cache: Any = None


def set_backend(backend: Any = None) -> None:
    """Install a bridge stand-in (tests). Mirrors the Java static API."""
    global _backend
    _backend = backend


def clear_backend() -> None:
    global _backend, _cache, _probed
    _backend = None
    _cache = None
    _probed = False


def reset_state() -> None:
    """Drop the bridge cache and every stored suggestion (tests)."""
    global _cache, _probed
    _cache = None
    _probed = False


def _bridge() -> Any:
    global _cache, _probed
    if _backend is not None:
        return _backend
    if not _probed:
        _probed = True
        try:
            from ai.jarvis.assistant.whatsapp import WhatsAppBridge  # type: ignore

            _cache = WhatsAppBridge
        except Exception:  # noqa: BLE001 - not running inside the Android app
            _cache = None
    return _cache


def is_supported() -> bool:
    """True when running inside the Android app (bridge importable)."""
    return _bridge() is not None


def _as_dict(value: Any) -> Dict[str, Any]:
    if isinstance(value, str):
        try:
            data = json.loads(value)
            return data if isinstance(data, dict) else {"ok": False, "error": "bad bridge payload"}
        except Exception:  # noqa: BLE001
            return {"ok": False, "error": value[:200]}
    if isinstance(value, dict):
        return value
    return {"ok": False, "error": "unexpected bridge return"}


def _call(bridge: Any, method: str, payload: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    fn = getattr(bridge, method)
    try:
        raw = fn(json.dumps(payload)) if payload is not None else fn()
    except Exception as exc:  # noqa: BLE001
        raise WhatsAppError(f"whatsapp bridge failed: {exc}", 400) from exc
    data = _as_dict(raw)
    if not data.get("ok"):
        raise WhatsAppError(str(data.get("error") or "whatsapp bridge error"), 400)
    return data


def bridge_status() -> Dict[str, Any]:
    """Listener/reply-target report from the Android bridge."""
    bridge = _bridge()
    if bridge is None:
        return {"supported": False}
    try:
        data = _call(bridge, "status")
    except WhatsAppError as exc:
        return {"supported": True, "error": str(exc)}
    data["supported"] = True
    return data


def send_reply(chat: str, text: str) -> Dict[str, Any]:
    """Send a reply through WhatsApp's reply action (Android only)."""
    chat = (chat or "").strip()
    text = (text or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    if not text:
        raise WhatsAppError("reply text is required")
    bridge = _bridge()
    if bridge is None:
        raise WhatsAppError("sending replies requires the Android app", 409)
    data = _call(bridge, "reply", {"chat": chat, "text": text[:MAX_REPLY_CHARS]})
    record_message(chat, text, direction="out", source="live")
    return data


