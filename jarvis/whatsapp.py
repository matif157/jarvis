def _month(name: str) -> int:
    return MONTHS.get(name.strip().lower()[:9], 0)


def _fmt(year: int, month: int, day: int, hour: int, minute: int, meridiem: str) -> str:
    if meridiem:
        hour24 = hour % 12
        if meridiem.lower().startswith("p"):
            hour24 += 12
        hour = hour24
    if month > 12 and day <= 12:
        month, day = day, month  # US-style m/d/y with an impossible month
    if year < 100:
        year += 2000 if year < 70 else 1900
    try:
        return datetime(year, month, day, hour, minute).strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return ""


def _split_sender(body: str) -> tuple:
    """``Sender: text`` -> (sender, text); system lines -> ("", body)."""
    if ": " in body:
        sender, text = body.split(": ", 1)
        if 0 < len(sender) <= 60 and text.strip():
            return sender.strip(), text.strip()
    return "", body.strip()


def parse_export(content: str) -> List[Dict[str, Any]]:
    """Parse a WhatsApp export .txt into message dicts (no chat key yet)."""
    messages: List[Dict[str, Any]] = []
    current: Optional[Dict[str, Any]] = None
    for raw in (content or "").replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        line = raw.rstrip()
        if not line:
            continue
        match = LINE_RE.match(line)
        if match:
            day, month, year = int(match.group(1)), int(match.group(2)), int(match.group(3))
            ts = _fmt(year, month, day, int(match.group(4)), int(match.group(5)), match.group(6) or "")
            current = _new_export_msg(_split_sender(match.group(7)), ts)
            messages.append(current)
            continue
        match = DAY_FIRST_RE.match(line)
        if match:
            month = _month(match.group(2))
            ts = _fmt(int(match.group(3)), month, int(match.group(1)), int(match.group(4)), int(match.group(5)), match.group(6) or "")
            current = _new_export_msg(_split_sender(match.group(7)), ts)
            messages.append(current)
            continue
        match = MONTH_FIRST_RE.match(line)
        if match:
            month = _month(match.group(1))
            ts = _fmt(int(match.group(3)), month, int(match.group(2)), int(match.group(4)), int(match.group(5)), match.group(6) or "")
            current = _new_export_msg(_split_sender(match.group(7)), ts)
            messages.append(current)
            continue
        if current is not None:  # multi-line message continuation
            current["text"] = (current["text"] + " " + line.strip())[:MAX_TEXT]
    return [m for m in messages if m["text"]]


def _new_export_msg(split: tuple, ts: str) -> Dict[str, Any]:
    sender, text = split
    direction = "out" if sender.strip().lower() in SELF_SENDERS else ("system" if not sender else "in")
    return {"sender": sender, "direction": direction, "text": text[:MAX_TEXT], "ts": ts}


def _chat_from_filename(name: str) -> str:
    stem = Path(name).name
    for ext in (".txt", ".zip"):
        if stem.lower().endswith(ext):
            stem = stem[: -len(ext)]
    if stem.lower().startswith("whatsapp chat with "):
        return stem[18:].strip() or "WhatsApp Chat"
    if stem.lower() in ("_chat", "chat"):
        return "WhatsApp Chat"
    return stem.strip() or "WhatsApp Chat"


def _read_export(path: Path) -> tuple:
    """Return (text, filename) from a .txt or a .zip's first .txt entry."""
    if path.suffix.lower() == ".zip":
        with zipfile.ZipFile(path) as zf:
            names = [n for n in zf.namelist() if n.lower().endswith(".txt") and not n.endswith("/")]
            if not names:
                raise WhatsAppError("no .txt chat file inside the zip archive")
            with zf.open(names[0]) as fh:
                return fh.read().decode("utf-8", errors="replace"), names[0]
    return path.read_text(encoding="utf-8", errors="replace"), path.name


def import_export(path: str, chat: Optional[str] = None) -> Dict[str, Any]:
    """Import a WhatsApp export file; returns stored/skipped counts."""
    if not (path or "").strip():
        raise WhatsAppError("path is required")
    if not is_path_safe(path) or not Path(path).is_file():
        raise WhatsAppError("export file not found or not allowed")
    try:
        content, filename = _read_export(Path(path))
    except WhatsAppError:
        raise
    except (OSError, UnicodeDecodeError, zipfile.BadZipFile) as exc:
        raise WhatsAppError(f"could not read export file: {exc}") from None
    messages = parse_export(content)
    if not messages:
        raise WhatsAppError("no messages recognised in the export file")
    chat_name = (chat or "").strip() or _chat_from_filename(filename)
    added = 0
    for msg in messages:
        if record_message(
            chat_name,
            msg["text"],
            direction=msg["direction"],
            sender=msg["sender"],
            ts=msg["ts"],
            source="export",
        ):
            added += 1
    return {
        "chat": chat_name,
        "parsed": len(messages),
        "added": added,
        "skipped": len(messages) - added,
        "duplicates": len(messages) - added,
    }


