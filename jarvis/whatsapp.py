LISTEN_SETTING = "whatsapp.listen"          # default on
AUTO_REPLY_SETTING = "whatsapp.auto_reply"  # master switch, default off
RULES_SETTING = "whatsapp.rules"            # JSON {chat: off|suggest|auto}
COOLDOWN_SETTING = "whatsapp.cooldown"      # seconds between auto replies

DEFAULT_COOLDOWN = 60
MAX_TEXT = 4000
TRANSCRIPT_CHARS = 1000  # chat history fed to the model
MAX_REPLY_CHARS = 1000
RULE_MODES = ("off", "suggest", "auto")
SELF_SENDERS = ("you", "me", "(you)")
SUGGEST_KEY = "wa:suggest:{chat}"

