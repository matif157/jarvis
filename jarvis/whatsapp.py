"""WhatsApp bridge (Phase 22).

Reads WhatsApp messages and replies, governed by per-contact rules.

Two official inputs feed the ``wa_messages`` table (see :mod:`jarvis.db`):

* **Live** - the Android app's notification listener
  (``ai.jarvis.assistant.whatsapp.WhatsAppListener``) posts each message to
  ``/api/whatsapp/event``; :func:`handle_event` records it and applies the
  reply rules.
* **Export** - a WhatsApp "Export chat" ``.txt``/``.zip`` file imported through
  :func:`import_export`, which builds the full structure of a chat (or all
  chats) offline.

Replies are generated by the configured chat provider (``llm.complete``) and
can be sent through the Android reply bridge, but only when the chat's rule
(``off`` / ``suggest`` / ``auto``) and the master switch allow it. A suggestion
is stored under the memory key ``wa:suggest:{chat}`` until accepted or
dismissed.

Everything degrades honestly off-device: the bridge reports
``supported: false`` and reply calls fail with a 409-style
:class:`WhatsAppError`.
"""

