def _normalize_ts(ts: Any) -> str:
    """Normalise a timestamp to sortable ``YYYY-MM-DD HH:MM`` (local/UTC mix)."""
    if ts is None:
        return ""
    if isinstance(ts, (int, float)) or (isinstance(ts, str) and ts.strip().isdigit()):
        try:
            return datetime.fromtimestamp(float(ts) / (1000.0 if float(ts) > 1e11 else 1.0)).strftime(
                "%Y-%m-%d %H:%M"
            )
        except (OverflowError, OSError, ValueError):
            return ""
    text = str(ts).strip()
    if not text:
        return ""
    text = text.replace("T", " ").replace("Z", "")
    if len(text) >= 16 and text[4] == "-" and text[7] == "-":
        return text[:16]
    return text[:16]


def make_hash(chat: str, direction: str, text: str, ts: str) -> str:
    """Content hash at minute granularity (export + live overlap dedupe)."""
    minute = (ts or "")[:16]
    raw = f"{chat}|{direction}|{text}|{minute}"
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()


def record_message(
    chat: str,
    text: str,
    direction: str = "in",
    sender: str = "",
    ts: Any = "",
    source: str = "live",
) -> bool:
    """Store one message; False when the same message already exists."""
    chat = (chat or "").strip()
    text = re.sub(r"\s+", " ", (text or "").strip())
    if not chat or not text or len(text) > MAX_TEXT:
        return False
    if direction not in ("in", "out", "system"):
        direction = "in"
    ts_s = _normalize_ts(ts) if ts else db.now()[:16].replace("T", " ")
    if not ts_s:
        ts_s = db.now()[:16].replace("T", " ")
    return db.add_wa_message_db(
        {
            "chat": chat,
            "sender": (sender or "").strip()[:80],
            "direction": direction,
            "text": text,
            "ts": ts_s,
            "source": source if source in ("live", "export") else "live",
            "hash": make_hash(chat, direction, text, ts_s),
        }
    )


def record_event(event: Dict[str, Any]) -> Dict[str, Any]:
    """Record one live notification event (gated by ``whatsapp.listen``)."""
    if not get_listen():
        return {"ok": True, "stored": False, "reason": "listening is disabled"}
    chat = str(event.get("chat") or "").strip()
    text = str(event.get("text") or "").strip()
    if not chat:
        raise WhatsAppError("chat is required")
    if not text:
        return {"ok": True, "stored": False, "reason": "empty message"}
    ts = event.get("ts_ms") or event.get("ts") or ""
    stored = record_message(
        chat,
        text,
        direction="in",
        sender=str(event.get("sender") or ""),
        ts=ts,
        source="live",
    )
    return {
        "ok": True,
        "stored": stored,
        "chat": chat,
        "text": text[:200],
        "can_reply": bool(event.get("can_reply")),
    }


