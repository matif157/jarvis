def get_listen() -> bool:
    return (db.get_setting(LISTEN_SETTING, "1") or "1").strip().lower() not in ("0", "false", "off")


def get_auto_reply() -> bool:
    return (db.get_setting(AUTO_REPLY_SETTING, "0") or "0").strip().lower() in ("1", "true", "on")


def get_cooldown() -> int:
    raw = (db.get_setting(COOLDOWN_SETTING, str(DEFAULT_COOLDOWN)) or "").strip()
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return DEFAULT_COOLDOWN
    return max(0, min(value, 86400))


def get_rules() -> Dict[str, str]:
    """Per-chat reply rules; tolerant of a corrupt setting."""
    raw = db.get_setting(RULES_SETTING, "") or ""
    if not raw.strip():
        return {}
    data: Any = None
    try:
        data = json.loads(raw)
    except Exception:  # noqa: BLE001
        try:
            data = ast.literal_eval(raw)
        except Exception:  # noqa: BLE001
            logger.warning("Ignoring corrupt whatsapp.rules setting")
            return {}
    if not isinstance(data, dict):
        return {}
    return {
        str(k): str(v).strip().lower()
        for k, v in data.items()
        if str(k).strip() and str(v).strip().lower() in RULE_MODES
    }


def rule_for(chat: str) -> str:
    return get_rules().get((chat or "").strip(), "off")


def apply_settings(
    listen: Optional[bool] = None,
    auto_reply: Optional[bool] = None,
    rules: Optional[Dict[str, Any]] = None,
    cooldown: Optional[int] = None,
) -> Dict[str, Any]:
    """Persist WhatsApp settings; returns the effective configuration."""
    if rules is not None:
        if not isinstance(rules, dict):
            raise WhatsAppError("rules must be an object of chat -> mode")
        cleaned: Dict[str, str] = {}
        for chat, mode in rules.items():
            chat_name = str(chat).strip()
            mode_s = str(mode).strip().lower()
            if not chat_name:
                raise WhatsAppError("rule chat name cannot be empty")
            if mode_s not in RULE_MODES:
                raise WhatsAppError(f"unknown rule mode: {mode} (use off, suggest or auto)")
            cleaned[chat_name] = mode_s
        db.set_setting(RULES_SETTING, json.dumps(cleaned, ensure_ascii=False))
    if listen is not None:
        db.set_setting(LISTEN_SETTING, "1" if listen else "0")
    if auto_reply is not None:
        db.set_setting(AUTO_REPLY_SETTING, "1" if auto_reply else "0")
    if cooldown is not None:
        try:
            value = int(cooldown)
        except (TypeError, ValueError):
            raise WhatsAppError("cooldown must be a number of seconds") from None
        if value < 0 or value > 86400:
            raise WhatsAppError("cooldown must be between 0 and 86400 seconds")
        db.set_setting(COOLDOWN_SETTING, str(value))
    return settings_payload()


def settings_payload() -> Dict[str, Any]:
    return {
        "listen": get_listen(),
        "auto_reply": get_auto_reply(),
        "cooldown": get_cooldown(),
        "rules": get_rules(),
    }


